"""distance2.py - appendix figure "Distance >= 2 protocol" (figA_distance2): Unseen-detection AUC of the method under the usual open-set protocol and under the distance >= 2 protocol.
Source: results/open_set/distance2.json: the method's detector on the distance >= 2 protocol (124 cells = 31 pairs x 4 draws) and, paired, on the SAME 124 cells of the usual protocol;
usual protocol = auc_usual, distance >= 2 = auc_dtwo; {N_t: [mean over pairs of pair means, SE over pairs]}.
  python -m paper.figures.distance2 [--out DIR]
Writes <out>/figA_distance2.{pdf,png,json} and <out>/distance2_numbers.tex (the \\nDtw... macros of the paper); default <out> = the figures directory of the output root."""
import argparse, json, os
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from ..dataio import R, GRID, XL_NT, data_root, fig_dir, style
from ..common import COL, jdump


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0]); ap.add_argument("--out", default=None, help="output directory (default: <FLIPS_OUT>/figures)"); a = ap.parse_args(argv)
    out = a.out or fig_dir(); os.makedirs(out, exist_ok=True); SRC = R("open_set", "distance2.json")
    style(); J = json.load(open(SRC)); AU, AD = J["auc_usual"], J["auc_dtwo"]; nts = sorted(int(k) for k in AU); assert nts == sorted(int(k) for k in AD)
    fig, ax = plt.subplots(figsize=(COL, 2.3))
    for A, lab, col in ((AU, "usual protocol", "#1f77b4"), (AD, "distance $\\geq 2$ protocol", "red")):
        ax.errorbar(nts, [A[str(n)][0] for n in nts], yerr=[A[str(n)][1] for n in nts], color=col, marker="o", ms=3.2, lw=1.4, capsize=1.2, elinewidth=0.6, label=lab)
    ax.axhline(0.5, color="black", ls=":", lw=0.8)
    ax.set_xscale("log", base=2); ax.set_xticks(nts); ax.set_xticklabels([str(n) for n in nts]); ax.minorticks_off(); ax.set_xlim(.85, 75)
    ax.set_xlabel(XL_NT); ax.set_ylabel("Unseen-detection AUC"); ax.set_ylim(0.48, 0.9); ax.grid(**GRID)
    ax.legend(fontsize=6.3, frameon=False, loc="upper left", handlelength=2.0, labelspacing=.25); fig.tight_layout()
    for ext, kw in (("pdf", {}), ("png", dict(dpi=200))): fig.savefig(os.path.join(out, f"figA_distance2.{ext}"), **kw)
    plt.close(fig)
    macros = {"AucUsualThirtyTwo": AU["32"][0], "AucDtwoThirtyTwo": AD["32"][0]}       # the AUC of the two protocols at N_t 32, quoted in the text
    with open(os.path.join(out, "distance2_numbers.tex"), "w") as f:
        f.write("% generated by paper/figures/distance2.py from results/open_set/distance2.json: do not edit\n")
        for k, v in macros.items(): f.write("\\newcommand{\\nDtw%s}{%s}\n" % (k, ("%.4f" % v).rstrip("0").rstrip(".") if isinstance(v, float) else v))
    jdump(dict(source=os.path.relpath(SRC, data_root()), note="usual = same 124 cells of the usual protocol (draws 0-3), distance >= 2 = distance >= 2 protocol; same detector on both; mean over 31 pairs, SE over pairs",
               auc_usual=AU, auc_dtwo=AD), os.path.join(out, "figA_distance2.json"))
    print(macros)


if __name__ == "__main__":
    main()
