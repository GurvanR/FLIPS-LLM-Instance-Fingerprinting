"""attribute_errors.py - the attribute analysis of the closed set (hierarchical classifier, N_t 32, 237 instances).

Step 1: attr_numbers.json (error counts, and per attribute the share of the errors that keep its true value) and attr_numbers.tex (the \\fgAttr... macros of the paper),
from the closed-set confusion of predictions.json (lib/attributes.py).
Step 2: attr_error_matrices.{pdf,png} + attr_miss.json: one bar per attribute = how often FLIPS misses the attribute, as a share of how often an instance drawn at random would miss it.
  flips_miss(k)  = share of ALL closed-set samples whose predicted instance has a different value of attribute k than the true instance;
  random_miss(k) = the same share if the predicted instance were drawn uniformly among the 237 instances (true one included), samples weighted as in the data;
  bar = flips_miss / random_miss (0 % never missed, 100 % missed as often as at random).
Guard: flips_miss must equal error rate * (1 - kept) of attr_numbers.json (4 dp), else the step stops before writing.
  python -m paper.figures.attribute_errors
Writes <out>/figures/attr_numbers.{json,tex}, attr_error_matrices.{pdf,png} (the four-bar figure, 5.4 in wide), attr_miss.json."""
import argparse, json, os
import numpy as np
import matplotlib.pyplot as plt
from ..dataio import ATTR, Ctx, Skip, attrs, fig_dir, load_post, post_confusion, r4
from ..lib import attributes as FA

NAME = "attr_error_matrices"
NT, NR = 32, 300
LABEL = FA.TITLE
BLUE, INK = "#08519c", "0.15"
W = 5.4                                                                           # figure width (in): the paper includes it at this size
XMAX = 30                                                                         # right end of the plotted scale (%): every bar is far below 100 %
YK, PAD = -0.95, 17                                                               # height of the key line (data units, rows at 0..3) and title pad (pt) above it


def numbers(ctx, D):
    N = dict(classes=D["C"], n_batches=D["n_batches"], n_errors=D["n_errors"], accuracy=r4(D["accuracy"]), error_rate=r4(D["error_rate"]), attributes={})
    for k in ATTR:
        d = D["attributes"][k]
        N["attributes"][k] = dict(same_value_share_pooled=r4(d["keep"]), chance_same_value_pooled=r4(d["keep_chance"]))
    N["_build"] = dict(nr=ctx.nr, nt=ctx.nt, note=f"closed set, N_t {ctx.nt}, errors only (stored confusion); same_value_share_pooled = share of all errors that keep the true value of the attribute; "
                       "chance_same_value_pooled = the same share if each error went to a uniformly drawn wrong instance (error-weighted)")
    return N


def write_tex(ctx, D, path):
    """the \\fgAttr... macros of the paper: number of instances and N_t"""
    mac = [("Classes", D["C"]), ("Nt", ctx.nt)]
    with open(path, "w") as f: f.write("% generated by paper/figures/attribute_errors.py: do not edit\n" + "\n".join(f"\\newcommand{{\\fgAttr{n}}}{{{v}}}" for n, v in mac) + "\n")


def load_stored():
    """attr_numbers.json written by step 1 -> (the numbers, {attribute: kept / chance share of the errors})"""
    with open(os.path.join(fig_dir(), "attr_numbers.json")) as f: N = json.load(f)
    rows = {k: dict(keep=N["attributes"][k]["same_value_share_pooled"], chance=N["attributes"][k]["chance_same_value_pooled"]) for k in ATTR}
    return N, rows


def inch_axes(fig, H, x, y, w, h): return fig.add_axes([x / W, 1 - (y + h) / H, w / W, h / H])     # y from the top


def spines(ax):
    for s in ("left", "top", "right"): ax.spines[s].set_visible(False)
    ax.spines["bottom"].set_linewidth(0.6); ax.spines["bottom"].set_color("0.4"); ax.spines["bottom"].set_bounds(0, 100)
    ax.tick_params(axis="x", length=2.5, width=0.6, pad=2, labelsize=7.5, color="0.4"); ax.tick_params(axis="y", length=0)
    ax.set_xticks([0, 25, 50, 75, 100]); ax.grid(axis="x", color="0.88", lw=0.5, ls="--", zorder=0); ax.set_axisbelow(True)


def compute():
    N, rows = load_stored()
    ctx = Ctx(fig_dir(), nr=NR, nt=NT); cl, _ = load_post(ctx); M = post_confusion(ctx, cl, NT); names = ctx.names; C = len(names)
    A = [attrs(n) for n in names]; tot = M.sum(); w = M.sum(1) / tot; out = {}; bad = 0
    assert (C, int(tot), int(tot - np.trace(M))) == (N["classes"], N["n_batches"], N["n_errors"]), "confusion does not match attr_numbers.json"
    for k, key in enumerate(ATTR):
        vals = [a[k] for a in A]; diff = np.array([[vals[i] != vals[j] for j in range(C)] for i in range(C)])
        fm = float((M * diff).sum() / tot); rm = float((w * diff.sum(1) / C).sum()); stored = N["n_errors"] / N["n_batches"] * (1 - rows[key]["keep"])
        ok = abs(fm - stored) < 5e-5; bad += not ok
        out[key] = dict(label=LABEL[key], flips_miss=round(fm, 4), random_miss=round(rm, 4), ratio=round(fm / rm, 4))
        print(f"  {'OK  ' if ok else 'DIFF'} {LABEL[key]:<14} FLIPS misses {100 * fm:5.2f} % (stored {100 * stored:5.2f} %) | random instance {100 * rm:5.2f} % | ratio {100 * fm / rm:5.1f} %")
    if bad: raise RuntimeError(f"{bad} MISMATCH(ES): nothing written")
    return dict(attributes=out, n_samples=int(tot), n_instances=C, nt=NT,
                note="closed set, hierarchical instance classifier, N_t 32; flips_miss = share of all samples whose predicted instance has the wrong value of the attribute; "
                     "random_miss = same share for a predicted instance drawn uniformly among the 237 instances (true one included); ratio = flips_miss / random_miss",
                source=dict(confusion="results/closed_set/hierarchical/predictions.json (confusion[\"32\"])", script="paper/figures/attribute_errors.py"))


def draw(J):
    R = J["attributes"]; order = sorted(R, key=lambda k: -R[k]["ratio"]); n = len(order); y = np.arange(n)        # most missed on top
    top, rh, bot = 0.50, 0.30, 0.40; hA = n * rh; H = top + hA + bot; lm = 1.04
    fig = plt.figure(figsize=(W, H), dpi=200); wa = W - lm - 0.55
    ax = inch_axes(fig, H, lm, top, wa, hA); spines(ax); ax.spines["bottom"].set_bounds(0, XMAX); ax.set_ylim(n - 0.5, -0.5)
    for i, k in enumerate(order):
        g = 100 * R[k]["ratio"]
        ax.barh(i, g, height=0.6, color=BLUE, lw=0, zorder=2)
        ax.text(g + 0.45, i, f"{g:.0f}%", va="center", ha="left", fontsize=8.5, fontweight="bold", color=BLUE, zorder=3)
    ax.axvline(0, color=INK, lw=0.9, zorder=3)
    ax.set_yticks(y); ax.set_yticklabels([R[k]["label"] for k in order], fontsize=8.5, color=INK)
    ax.set_xticks(range(0, XMAX + 1, 10)); ax.set_xlim(-0.6, XMAX + 1.2)
    ax.set_xlabel("Misses of FLIPS, relative to an instance drawn at random (%)", fontsize=8, labelpad=2, color=INK)
    ax.set_title("How often does FLIPS miss each attribute?", loc="left", fontsize=9, fontweight="bold", pad=PAD)
    tk = dict(va="center", fontsize=7.5, color="0.25", clip_on=False)
    ax.text(0, YK, "0% = never missed;  100% = missed as often as random", ha="left", **tk)
    return fig


def main(argv=None):
    ap = argparse.ArgumentParser(description="attribute numbers (attr_numbers.json/.tex) and the attribute figure (attr_error_matrices, attr_miss.json)")
    ap.add_argument("--data", help="data root (default: $FLIPS_DATA)"); ap.add_argument("--out", help="output root (default: $FLIPS_OUT)")
    a = ap.parse_args(argv)
    if a.data: os.environ["FLIPS_DATA"] = a.data
    if a.out: os.environ["FLIPS_OUT"] = a.out
    out = fig_dir(); ctx = Ctx(out, nr=NR, nt=NT)
    try: D = FA.attr_data(ctx)
    except Skip as e: raise SystemExit(f"[skip] {e}")
    with open(os.path.join(out, "attr_numbers.json"), "w") as f: json.dump(numbers(ctx, D), f, indent=1)
    write_tex(ctx, D, os.path.join(out, "attr_numbers.tex"))
    J = compute()
    with open(os.path.join(out, "attr_miss.json"), "w") as f: json.dump(J, f, indent=1)
    with plt.rc_context():                                                       # matplotlib defaults + exact size, no bbox cropping; rcParams restored afterwards
        plt.rcdefaults(); plt.rcParams.update({"font.family": "DejaVu Sans", "pdf.fonttype": 42, "ps.fonttype": 42, "savefig.bbox": None})
        fig = draw(J); fig.savefig(os.path.join(out, NAME + ".pdf")); fig.savefig(os.path.join(out, NAME + ".png"), dpi=200)
    plt.close(fig)
    print(f"[ok] {NAME}.pdf/.png  {fig.get_size_inches()[0]:.2f} x {fig.get_size_inches()[1]:.2f} in -> {out}")


if __name__ == "__main__":
    main()
